"""Regenerate characters.js and releases.js from tools/characters.source.json and tools/titles.json.

Usage: python3 tools/build_data.py

titles.json lists every film/show in release order as [title, phase].
Each character in characters.source.json looks like:
  {
    "name": ["Tony", "Stark", "(Iron Man)"],   # name parts; wrap an alias in parens
    "debut": "Iron Man",                        # must match a title in titles.json
    "affiliation": ["Avengers", "Stark Industries"],
    "species": ["Human"],                       # species, then optional subtype, e.g. ["Human", "Enhanced"]
    "gender": "Male",
    "role": "Hero",                             # Hero / Villain / Anti-hero / Neutral
    "status": "Dead"                            # Alive / Dead, as of their latest appearance
  }
"""
import json, pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
titles = json.loads((root / "tools" / "titles.json").read_text())
known = {t for t, _ in titles}
src = json.loads((root / "tools" / "characters.source.json").read_text())
keep = ["name", "debut", "affiliation", "species", "gender", "role", "status"]
out, names = [], set()
for i, c in enumerate(src):
    missing = [k for k in keep if k != "affiliation" and k not in c]
    if missing:
        sys.exit(f"entry {i} ({c.get('name')}) is missing {missing}")
    if c["debut"] not in known:
        sys.exit(f"{' '.join(c['name'])}: debut {c['debut']!r} is not in tools/titles.json")
    key = " ".join(c["name"]).lower()
    if key in names:
        sys.exit(f"duplicate character: {key}")
    names.add(key)
    out.append({k: c.get(k, []) for k in keep})
head = "// Generated by tools/build_data.py — edit tools/*.json instead.\n"
(root / "characters.js").write_text(head + "window.CHARACTERS = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
(root / "releases.js").write_text(head + "window.RELEASES = " + json.dumps(titles, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"wrote {len(out)} characters, {len(titles)} titles")
